from __future__ import annotations

import json
import os
from pathlib import Path

from k2websdr.protocol import stream as sv

ROOT = Path(__file__).resolve().parents[2]
PATH = ROOT / "protocol/vectors/stream_v1.json"


def build() -> dict:
    spec = sv.SpectrumInfo(-127500, 500, 14)
    aud = sv.AudioInfo(-4321, 300, 2700, 2, 3)
    valid = [
        ("spectrum", sv.pack(sv.Kind.SPECTRUM, sv.Flags.NEW_GEN, 7, 384000, 7_074_000, 384000, "replay-0", spec,
                             bytes([0, 1, 2, 254, 255]))),
        ("audio", sv.pack(sv.Kind.AUDIO, sv.Flags.DISCONTINUITY | sv.Flags.SERVER_DROP, 2**53 - 1, 12,
                          10_000_000_000, 12000, "ch_12", aud, b"\x01\x00\xff\xff\xff\x7f\x00\x80")),
        ("audio_id_64", sv.pack(sv.Kind.AUDIO, 0, 1, 0, 0, 12000, "ch_" + "a" * 32, aud, b"")),
        ("spectrum_negative_freq", sv.pack(sv.Kind.SPECTRUM, 0, 1, 0, -1, 48000, "x", spec, b"\x07")),
    ]
    good = valid[0][1]
    invalid = [
        ("short", good[:63]), ("bad_magic", b"XXXX" + good[4:]), ("bad_version", good[:4] + b"\x02" + good[5:]),
        ("bad_kind", good[:5] + b"\x03" + good[6:]), ("undefined_flag", good[:8] + b"\x08\0\0\0" + good[12:]),
        ("reserved_nonzero", good[:61] + b"\x01" + good[62:]), ("payload_short", good[:-1]),
        ("id_padding_nonzero", valid[1][1][:70] + b"\x01" + valid[1][1][71:]),   # "ch_12": 5 bytes + 3 padding
    ]
    out_valid = []
    for name, b in valid:
        m = sv.unpack(b)
        exp = {"kind": int(m.kind), "flags": int(m.flags), "gen": m.gen, "sample_index": m.sample_index,
               "frequency_hz": m.frequency_hz, "sample_rate_hz": m.sample_rate_hz, "id": m.id}
        if m.kind is sv.Kind.SPECTRUM:
            exp.update(db_floor_mdb=m.info.db_floor_mdb, db_step_mdb=m.info.db_step_mdb, blocks=m.info.blocks,
                       bins=list(m.payload))
        else:
            import struct
            exp.update(level_cdb=m.info.level_cdb, pass_lo_hz=m.info.pass_lo_hz, pass_hi_hz=m.info.pass_hi_hz,
                       mode=m.info.mode, agc=m.info.agc, pcm=list(struct.unpack(f"<{m.count}h", m.payload)))
        out_valid.append({"name": name, "hex": b.hex(), "expect": exp})
    out_invalid = []
    for name, b in invalid:
        if name == "skip":
            continue
        try:
            sv.unpack(b)
        except sv.StreamError:
            out_invalid.append({"name": name, "hex": b.hex()})
        else:
            raise AssertionError(f"{name} unexpectedly decodes")
    return {"description": "Browser stream v1 (docs/protocol/stream-v1.md). Generated by "
                           "control/tests/test_stream_vectors.py; decoders must accept every valid case with "
                           "the expected fields and refuse every invalid one.",
            "version": 1, "valid": out_valid, "invalid": out_invalid}


def test_committed_stream_vectors_are_current():
    text = json.dumps(build(), indent=1) + "\n"
    if os.environ.get("K2_WRITE_VECTORS") == "1":
        PATH.write_text(text)
    assert PATH.read_text() == text, "stale: regenerate with K2_WRITE_VECTORS=1 (see module docstring)"
